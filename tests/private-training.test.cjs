const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomBytes, createCipheriv, pbkdf2Sync, createHmac } = require('node:crypto');
const key = randomBytes(32), iv = randomBytes(12), cipher = createCipheriv('aes-256-gcm', key, iv);
const fixture = '<html><body>Private test fixture</body></html>';
const data = Buffer.concat([cipher.update(fixture), cipher.final()]);
const contentPath = require.resolve('../private/fitness.enc.json');
require.cache[contentPath] = { id: contentPath, filename: contentPath, loaded: true, exports: { iv: iv.toString('base64'), tag: cipher.getAuthTag().toString('base64'), data: data.toString('base64') } };
const passwordSalt = randomBytes(24).toString('base64');
const password = randomBytes(16).toString('base64url');
const config = { contentKey: key.toString('base64'), sessionSecret: randomBytes(32).toString('base64'), passwordSalt, passwordHash: pbkdf2Sync(password, passwordSalt, 310000, 32, 'sha256').toString('base64') };
const handler = require('../api/training.js');
const origin = 'https://private.example.test';
async function request(method = 'GET', options = {}) {
  let body = '', headers = {};
  const res = { statusCode: 200, setHeader(name, value) { headers[name.toLowerCase()] = value; }, end(value = '') { body = value; } };
  await handler({ method, headers: { host: 'private.example.test', 'x-forwarded-proto': 'https', 'x-forwarded-for': '127.0.0.2', ...options.headers }, body: options.body }, res);
  return { status: res.statusCode, headers, body };
}
test('private content is withheld, sessions are checked, and logout expires the cookie', async () => {
  delete process.env.FITNESS_PRIVATE_CONFIG;
  assert.equal((await request()).status, 503);
  process.env.FITNESS_PRIVATE_CONFIG = JSON.stringify(config);
  let result = await request();
  assert.equal(result.status, 200);
  assert(result.body.includes('type="password"'));
  assert(!result.body.includes('Private test fixture'));
  result = await request('POST', { headers: { origin }, body: { password: 'wrong' } });
  assert.equal(result.status, 401);
  assert(!result.body.includes('Private test fixture'));
  assert.equal((await request('POST', { headers: { origin: 'https://other.test' }, body: { password } })).status, 403);
  result = await request('POST', { headers: { origin }, body: { password } });
  assert.equal(result.status, 303);
  const setCookie = result.headers['set-cookie'];
  for (const flag of ['Secure', 'HttpOnly', 'SameSite=Strict', 'Path=/private']) assert(setCookie.includes(flag));
  const cookie = setCookie.split(';')[0];
  result = await request('GET', { headers: { cookie } });
  assert.equal(result.body, fixture);
  assert.equal(result.headers['cache-control'], 'private, no-store, max-age=0');
  assert(result.headers['x-robots-tag'].includes('noindex'));
  assert.equal((await request('HEAD', { headers: { cookie } })).body, '');
  assert((await request('GET', { headers: { cookie: cookie + 'tampered' } })).body.includes('type="password"'));
  const expired = Buffer.from(JSON.stringify({ exp: 1 })).toString('base64url');
  const signature = createHmac('sha256', config.sessionSecret).update(expired).digest('base64url');
  assert((await request('GET', { headers: { cookie: `__Secure-fitness_session=${expired}.${signature}` } })).body.includes('type="password"'));
  result = await request('POST', { headers: { origin, cookie }, body: { action: 'logout' } });
  assert.equal(result.status, 303);
  assert(result.headers['set-cookie'].includes('Max-Age=0'));
});
